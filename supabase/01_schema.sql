-- ---------- triggers ----------
create or replace function private.enforce_address_limit() returns trigger
language plpgsql set search_path = '' as $$
begin
  perform 1 from public.users where user_id = new.user_id for update;
  if (select count(*) from public.user_addresses where user_id = new.user_id) >= 3 then
    raise exception '배송지는 최대 3개까지 등록할 수 있습니다.';
  end if;
  return new;
end $$;
drop trigger if exists user_addresses_limit on public.user_addresses;
create trigger user_addresses_limit before insert on public.user_addresses
  for each row execute function private.enforce_address_limit();

create or replace function private.refresh_product_rating() returns trigger
language plpgsql set search_path = '' as $$
declare v_product bigint := coalesce(new.product_id, old.product_id);
begin
  update public.products p set
    rating_avg = s.avg_rating, rating_count = s.cnt
  from (select round(avg(rating), 2) avg_rating, count(*)::int cnt
        from public.reviews where product_id = v_product) s
  where p.product_id = v_product;
  return null;
end $$;
drop trigger if exists reviews_rating on public.reviews;
create trigger reviews_rating after insert or update or delete on public.reviews
  for each row execute function private.refresh_product_rating();

-- Grade counts real paid amounts of the last 3 months. Mock payments are excluded.
create or replace function private.recent_paid_amount(p_user bigint) returns bigint
language sql stable set search_path = '' as $$
  select coalesce(sum(pay.final_amount), 0)::bigint
  from public.payments pay join public.orders o using (order_id)
  where o.user_id = p_user and pay.pay_status = 'paid' and not pay.is_mock
    and pay.paid_at >= now() - interval '3 months';
$$;

create or replace function private.refresh_user_grade() returns trigger
language plpgsql set search_path = '' as $$
declare v_user bigint;
begin
  select user_id into v_user from public.orders where order_id = new.order_id;
  if v_user is null then return null; end if;
  update public.users set grade_code = (
    select grade_code from public.membership_grades
    where min_purchase_amount <= private.recent_paid_amount(v_user) order by min_purchase_amount desc limit 1
  ) where user_id = v_user;
  return null;
end $$;
drop trigger if exists payments_grade on public.payments;
create trigger payments_grade after insert or update on public.payments
  for each row execute function private.refresh_user_grade();

-- ---------- view ----------
create or replace view public.product_cards with (security_invoker = true) as
select
  p.product_id, p.name, p.price, p.discount_rate, p.sale_price, p.main_image_url,
  p.description, p.status, p.stock, p.popularity_score, p.rating_avg, p.rating_count, p.created_at,
  c.category_id, c.name as category_name, c.slug as category_slug,
  parent.category_id as parent_category_id, parent.name as parent_category_name, parent.slug as parent_slug,
  array(select i.image_url from public.product_images i where i.product_id = p.product_id order by i.sort_order) as image_urls,
  array(select o.option_value from public.product_options o where o.product_id = p.product_id and o.option_type = 'size' order by o.sort_order) as sizes,
  array(select o.option_value from public.product_options o where o.product_id = p.product_id and o.option_type = 'color' order by o.sort_order) as colors,
  array(select k.name from public.product_keywords pk join public.keywords k using (keyword_id) where pk.product_id = p.product_id) as keywords
from public.products p
join public.categories c on c.category_id = p.category_id
left join public.categories parent on parent.category_id = c.parent_id
where p.status <> 'hidden';

-- ---------- RLS ----------
do $$
declare t text;
begin
  -- Public catalog: read only
  foreach t in array array['membership_grades','shop_settings','categories','products','product_images','product_options','keywords','product_keywords','product_rankings','collections','collection_products'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select on public.%I to anon, authenticated', t);
    execute format('drop policy if exists public_read on public.%I', t);
    execute format('create policy public_read on public.%I for select to anon, authenticated using (%s)', t,
      case when t = 'products' then 'status <> ''hidden''' else 'true' end);
  end loop;
  -- Personal data: no direct access. Only the token-verified RPC functions reach these.
  foreach t in array array['users','user_addresses','cart_items','wishlist_items','orders','order_items','payments','order_claims','point_transactions','coupons','user_coupons','reviews','qna_posts'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;
grant select on public.product_cards to anon, authenticated;
revoke all on sequence public.order_number_seq, public.payment_number_seq from anon, authenticated;
